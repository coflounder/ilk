#!/bin/sh
# Routines: scheduled work held as documents, projected into whatever actually
# runs it.
#
#   ilk-routine.sh new "title"        write a routine document
#   ilk-routine.sh list               every routine, its schedule and its review date
#   ilk-routine.sh sync [--remove]    write the runner file from the documents
#   ilk-routine.sh run <id>           run one routine under its budget
#   ilk-routine.sh run --schedule C   run every active routine whose cron is C
#   ilk-routine.sh check-shape        fields a runner could act on
#   ilk-routine.sh check-current      the runner file matches the documents
#   ilk-routine.sh check-reviewed     nothing is running past its review date
#
# Nothing here remembers anything between runs. `run` is told what to run, either
# by name or by the cron expression that fired it, because the alternative —
# working out what is due — needs last-run state, and on an ephemeral runner that
# means committing from CI to find out what happened yesterday.
#
# Managed by ilk — edits are overwritten on the next `ilk apply`.
set -eu

dir="${ILK_VAR_GROUP:-docs}/${ILK_VAR_ROUTINES_DIR:-routines}"
runner=${ILK_VAR_RUNNER:-github}
workflow=${ILK_VAR_WORKFLOW:-.github/workflows/ilk-routines.yml}
crontab_file=${ILK_VAR_CRONTAB:-.ilk/routines.crontab}
root=${ILK_REPO_ROOT:-$(pwd)}

mode=${1:-}
[ $# -gt 0 ] && shift

# ---------------------------------------------------------------- reading

# fm prints one frontmatter scalar. Frontmatter only: a `budget:` mentioned in the
# prose is a sentence, not a declaration, and treating it as one would make the
# document say something its author never wrote.
fm() {
	awk -v want="$2" '
	NR == 1 { if ($0 ~ /^---[ \t]*$/) { inside = 1; next } else { exit } }
	!inside { next }
	$0 ~ /^---[ \t]*$/ { exit }
	{
		key = $0; sub(/:.*/, "", key); gsub(/[ \t]/, "", key)
		if (key != want) next
		val = $0; sub(/^[^:]*:[ \t]*/, "", val)
		sub(/[ \t]+$/, "", val)
		gsub(/^["'"'"']|["'"'"']$/, "", val)
		print val
		exit
	}
	' "$1"
}

# routines prints every routine file, sorted, so everything generated from them is
# byte-identical between machines. A projection that reorders itself would fail
# check-current for whoever ran sync second.
routines() {
	[ -d "$dir" ] || return 0
	find "$dir" -type f -name '*.md' | LC_ALL=C sort | while IFS= read -r file; do
		case "${file##*/}" in README.md) continue ;; esac
		echo "$file"
	done
}

slug() {
	printf '%s' "$1" |
		tr '[:upper:]' '[:lower:]' |
		sed -e 's/[^a-z0-9]\{1,\}/-/g' -e 's/^-//' -e 's/-$//' |
		cut -c1-60
}

day_number() {
	echo "$1" | awk -F- '{
		y = $1 + 0; m = $2 + 0; d = $3 + 0
		if (m <= 2) { y -= 1; m += 12 }
		era = int(y / 400); yoe = y - era * 400
		doy = int((153 * (m - 3) + 2) / 5) + d - 1
		doe = yoe * 365 + int(yoe / 4) - int(yoe / 100) + doy
		print era * 146097 + doe - 719468
	}'
}

# ---------------------------------------------------------------- generating

# workflow_body writes the GitHub projection. One file, one job, and dispatch by
# the cron string that fired — `github.event.schedule` carries it, so N routines
# share one workflow without ilk having to know which of them was due.
workflow_body() {
	# GitHub's expression syntax opens with the same two braces ilk's renderer does,
	# and ilk renders this script before it ever writes a workflow. Assembling the
	# opener here is what stops the renderer evaluating an expression meant for the
	# runner — and what keeps the escaping in one place instead of three.
	expr='${'"{"
	timeout=5
	entries=$(
		routines | while IFS= read -r file; do
			[ "$(fm "$file" status)" = active ] || continue
			printf '    - cron: "%s"  # %s — %s\n' \
				"$(fm "$file" schedule)" "$(fm "$file" id)" "$(fm "$file" title)"
		done
	)
	for file in $(routines); do
		[ "$(fm "$file" status)" = active ] || continue
		b=$(fm "$file" budget)
		case "$b" in *[!0-9]* | "") continue ;; esac
		[ "$b" -le "$timeout" ] || timeout=$b
	done

	cat <<EOF
# Generated by \`ilk routine sync\` from $dir/. Do not edit: \`ilk check\` reports
# the difference, and the next sync overwrites it. Change the routine instead.
#
# GitHub runs scheduled workflows from the default branch only, drops runs when the
# hour is busy, and stops scheduling entirely after 60 days with no repository
# activity. A routine that must not be missed needs something other than this.
name: ilk routines

on:
  schedule:
EOF
	if [ -n "$entries" ]; then
		printf '%s\n' "$entries"
	else
		echo "    []"
	fi
	cat <<EOF
  workflow_dispatch:
    inputs:
      id:
        description: The routine to run now
        required: false

concurrency:
  group: ilk-routines
  cancel-in-progress: false

jobs:
  run:
    runs-on: ubuntu-latest
    timeout-minutes: $((timeout + 5))
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0

      - name: Install ilk
        run: curl -fsSL https://raw.githubusercontent.com/coflounder/ilk/main/install.sh | sh

      # Through the environment rather than interpolated into the script body: one
      # of these is typed by whoever clicked the button, and pasting that straight
      # into a shell is how a workflow becomes a way to run anything.
      - name: Run what this trigger asked for
        env:
          ILK_ROUTINE_ID: $expr inputs.id }}
          ILK_ROUTINE_CRON: $expr github.event.schedule }}
        run: |
          if [ -n "\$ILK_ROUTINE_ID" ]; then
            ilk routine run "\$ILK_ROUTINE_ID"
          else
            ilk routine run --schedule "\$ILK_ROUTINE_CRON"
          fi
EOF
}

crontab_body() {
	cat <<EOF
# Generated by \`ilk routine sync\` from $dir/. Install with:
#
#     crontab $crontab_file
#
# Do not edit: \`ilk check\` reports the difference, and the next sync overwrites
# it. Change the routine instead.
EOF
	routines | while IFS= read -r file; do
		[ "$(fm "$file" status)" = active ] || continue
		printf '%s cd %s && ilk routine run %s  # %s\n' \
			"$(fm "$file" schedule)" "$root" "$(fm "$file" id)" "$(fm "$file" title)"
	done
}

generated() {
	case "$runner" in
	github) workflow_body ;;
	cron) crontab_body ;;
	esac
}

target() {
	case "$runner" in
	github) echo "$workflow" ;;
	cron) echo "$crontab_file" ;;
	esac
}

# ---------------------------------------------------------------- verbs

case "$mode" in
new)
	title=$*
	[ -n "$title" ] || { echo 'usage: ilk routine new "the routine"' >&2; exit 2; }
	name=$(slug "$title")
	[ -n "$name" ] || { echo "ilk routine: the title has no usable characters" >&2; exit 1; }
	[ -d "$dir" ] || { echo "ilk routine: no $dir/ directory — run \`ilk apply\` first" >&2; exit 1; }

	file="$dir/ROUTINE-$name.md"
	[ ! -e "$file" ] || { echo "ilk routine: $file already exists" >&2; exit 1; }

	# Six months out. Long enough not to be busywork, short enough that a routine
	# nobody wants any more is found in the same year it stopped being useful.
	review=$(awk -v d="$(day_number "$(date +%Y-%m-%d)")" 'BEGIN {
		z = d + 183 + 719468; era = int(z / 146097); doe = z - era * 146097
		yoe = int((doe - int(doe/1460) + int(doe/36524) - int(doe/146096)) / 365)
		doy = doe - (365 * yoe + int(yoe/4) - int(yoe/100))
		mp = int((5 * doy + 2) / 153); dd = doy - int((153 * mp + 2) / 5) + 1
		m = mp < 10 ? mp + 3 : mp - 9
		printf "%04d-%02d-%02d", yoe + era * 400 + (m <= 2), m, dd
	}')

	cat >"$file" <<EOF
---
id: $name
title: $title
status: active
schedule: "0 4 * * 1"
command: ilk check
budget: 15
owner: TODO
review_by: $review
---

# $title

## What this is for

<!-- The outcome, not the command. "The dependency audit is never more than a week
     old" is a reason to run something; "run npm audit" is not. -->

## Why it has to be scheduled

<!-- Scheduled work is work nobody is watching. If a hook, a check or a gate could
     catch this at the moment somebody caused it, that is strictly better: it fires
     when the fix is cheap and the author is still holding the context. Say why
     that is not available here. -->

## What happens when it fails

<!-- Who finds out, and what they do. A routine whose failure nobody sees is a
     routine that has already stopped working. -->
EOF

	echo "$file"
	echo
	echo "Set owner: to a person, then \`ilk routine sync\` to put it on the schedule."
	;;

list)
	found=0
	today=$(day_number "$(date +%Y-%m-%d)")
	for file in $(routines); do
		id=$(fm "$file" id)
		status=$(fm "$file" status)
		schedule=$(fm "$file" schedule)
		review=$(fm "$file" review_by)
		note=""
		case "$review" in
		[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9])
			left=$(($(day_number "$review") - today))
			[ "$left" -lt 0 ] && note="review overdue by $((0 - left))d"
			;;
		esac
		printf '%-8s %-16s %-24s %s\n' "$status" "$schedule" "$id" "$note"
		found=$((found + 1))
	done
	[ "$found" -gt 0 ] || echo "No routines. \`ilk routine new \"...\"\` writes one."
	;;

sync)
	if [ "${1:-}" = --remove ]; then
		[ "$runner" = none ] && exit 0
		f=$(target)
		[ -e "$f" ] || { echo "nothing to remove"; exit 0; }
		rm -f "$f"
		echo "removed $f"
		exit 0
	fi
	if [ "$runner" = none ]; then
		echo "runner is 'none' — nothing to write. Set the \`runner\` variable to github or cron."
		exit 0
	fi
	f=$(target)
	mkdir -p "$(dirname "$f")"
	generated >"$f"
	echo "wrote $f"
	;;

check-shape)
	report=$(
		ids=""
		for file in $(routines); do
			id=$(fm "$file" id)
			case " $ids " in
			*" $id "*) echo "$file: two routines share \`id: $id\` — \`ilk routine run\` cannot tell them apart" ;;
			esac
			[ -n "$id" ] && ids="$ids $id"

			status=$(fm "$file" status)
			case "$status" in
			active | paused) ;;
			*) echo "$file: \`status: $status\` is neither active nor paused" ;;
			esac

			budget=$(fm "$file" budget)
			case "$budget" in
			"" | *[!0-9]*) echo "$file: \`budget: $budget\` is not a whole number of minutes" ;;
			0) echo "$file: \`budget: 0\` would kill the routine before it started" ;;
			esac

			[ -n "$(fm "$file" command)" ] || echo "$file: \`command:\` is empty, so there is nothing to run"

			schedule=$(fm "$file" schedule)
			echo "$schedule" | awk -v f="$file" '
			{
				if (NF != 5) {
					printf "%s: `schedule: %s` is not five cron fields — @daily and named months are not accepted by the runners this is projected into\n", f, $0
					next
				}
				for (i = 1; i <= 5; i++)
					if ($i !~ /^[-0-9*,\/]+$/) {
						printf "%s: `schedule: %s` has a field (%s) that is not numeric cron\n", f, $0, $i
						next
					}
			}'
		done
	)
	[ -n "$report" ] || exit 0
	printf '%s\n' "$report"
	exit 1
	;;

check-current)
	[ "$runner" = none ] && exit 0
	f=$(target)
	want=$(generated)
	if [ ! -e "$f" ]; then
		# No routines and no file is a repository that has not started, not one
		# that has drifted.
		[ -z "$(routines)" ] && exit 0
		echo "$f: does not exist, but $dir/ has routines in it"
		exit 1
	fi
	if [ "$want" != "$(cat "$f")" ]; then
		echo "$f: does not match the routines in $dir/"
		exit 1
	fi
	exit 0
	;;

check-reviewed)
	today=$(day_number "$(date +%Y-%m-%d)")
	report=$(
		for file in $(routines); do
			review=$(fm "$file" review_by)
			case "$review" in
			[0-9][0-9][0-9][0-9]-[0-9][0-9]-[0-9][0-9]) ;;
			"")
				echo "$file: no \`review_by:\` date, so nothing will ever ask whether this is still wanted"
				continue
				;;
			*)
				echo "$file: \`review_by: $review\` is not a YYYY-MM-DD date"
				continue
				;;
			esac
			left=$(($(day_number "$review") - today))
			[ "$left" -lt 0 ] || continue
			echo "$file: was due to be reviewed $((0 - left)) day(s) ago ($review), and has been running unexamined since"
		done
	)
	[ -n "$report" ] || exit 0
	printf '%s\n' "$report"
	exit 1
	;;

run)
	id=""
	cron=""
	case "${1:-}" in
	--schedule)
		cron=${2:-}
		[ -n "$cron" ] || { echo "ilk routine run: --schedule needs a cron expression" >&2; exit 2; }
		;;
	"") echo "usage: ilk routine run <id> | --schedule '<cron>'" >&2; exit 2 ;;
	*) id=$1 ;;
	esac

	# A budget that silently does not apply is worse than no budget, so a missing
	# `timeout` is a failure rather than a licence to run unbounded.
	limit=timeout
	command -v timeout >/dev/null 2>&1 || limit=gtimeout
	command -v "$limit" >/dev/null 2>&1 || {
		echo "ilk routine run: no \`timeout\` command, so a routine's budget cannot be enforced." >&2
		echo "Install GNU coreutils (\`brew install coreutils\` provides gtimeout)." >&2
		exit 1
	}

	ran=0
	failed=0
	for file in $(routines); do
		if [ -n "$id" ]; then
			[ "$(fm "$file" id)" = "$id" ] || continue
		else
			[ "$(fm "$file" schedule)" = "$cron" ] || continue
			[ "$(fm "$file" status)" = active ] || continue
		fi

		name=$(fm "$file" id)
		budget=$(fm "$file" budget)
		cmd=$(fm "$file" command)
		echo "--- $name (budget ${budget}m): $cmd"
		ran=$((ran + 1))
		if "$limit" "${budget}m" sh -c "$cmd"; then
			echo "--- $name: ok"
		else
			code=$?
			failed=$((failed + 1))
			if [ "$code" -eq 124 ]; then
				echo "--- $name: killed at its ${budget}m budget" >&2
			else
				echo "--- $name: exited $code" >&2
			fi
		fi
	done

	if [ "$ran" -eq 0 ]; then
		if [ -n "$id" ]; then
			echo "ilk routine run: no routine with id '$id'" >&2
		else
			echo "ilk routine run: no active routine scheduled at '$cron'" >&2
		fi
		exit 1
	fi
	[ "$failed" -eq 0 ] || exit 1
	;;

*)
	cat >&2 <<'EOF'
usage: ilk routine new "the routine"     write a routine document
       ilk routine list                  every routine and when it must be reviewed
       ilk routine sync [--remove]       write the runner file from the documents
       ilk routine run <id>              run one routine under its budget
EOF
	exit 2
	;;
esac
